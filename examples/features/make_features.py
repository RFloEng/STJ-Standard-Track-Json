def lane_materials():
    (HERE / "lane_materials.xodr").write_text(XODR, encoding="utf-8", newline="\n")
    doc = {
        "_metadata": meta("No meshes: the surfaces come from the lane materials of an OpenDRIVE road, then the default."),
        "track_info": {"name": "STJ lane materials", "type": "point_to_point", "fictional": True},
        "reference": {"opendrive": {"uri": "lane_materials.xodr"}, **centerline(60, 4)},
        "surfaces": {"default": "concrete", "library": library(),
                     "opendrive_materials": {"tarmac_new": "asphalt", "verge": "grass", "loose": "gravel"}},
    }
    write_json(HERE / "lane_materials.stj.json", doc)


# ── OpenCRG ──────────────────────────────────────────────────────────────────

def crg():
    """A straight 10 m x 2 m grid, z = 0.001 u + 0.004 v (m), in the ASCII form of the OpenCRG sample files."""
    vs = [-1.0 + 0.5 * k for k in range(5)]
    lines = ["$CT", "STJ example: a 10 m by 2 m patch, z = 0.001 u + 0.004 v", "$", "$ROAD_CRG",
             "REFERENCE_LINE_START_U = 0.0", "REFERENCE_LINE_END_U = 10.0", "REFERENCE_LINE_INCREMENT = 1.0",
             "LONG_SECTION_V_RIGHT = -1.0", "LONG_SECTION_V_LEFT = 1.0", "LONG_SECTION_V_INCREMENT = 0.5", "$",
             "$KD_Definition", "#:LRFI"] + [f"D:long section {k},m" for k in range(1, len(vs) + 1)] + ["$", "$$$$"]
    for u in range(11):
        lines.append("".join(f"{0.001 * u + 0.004 * v:10.6f}" for v in vs))
    (HERE / "crg_patch.crg").write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    doc = {
        "_metadata": meta("An OpenCRG patch placed on a straight reference line (mode attached)."),
        "track_info": {"name": "STJ OpenCRG patch", "type": "point_to_point", "fictional": True},
        "reference": centerline(60, 4),
        "geometry": {"crg": [{"id": "patch", "uri": "crg_patch.crg", "s_start": 20.0, "s_end": 30.0, "mode": "attached",
                              "purpose": "elevation", "t_offset": 0.5, "z_offset": 0.01, "z_scale": 2.0}]},
        "surfaces": {"default": "asphalt", "library": library()},
    }
    write_json(HERE / "crg_patch.stj.json", doc)


def write_json(path, doc):
    path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8", newline="\n")


# ── a visual layer ───────────────────────────────────────────────────────────

def visual_layer():
    """40 m of road with a painted kerb and an infield: what draws and what the wheels touch in one file."""
    textures = HERE / "textures"
    textures.mkdir(exist_ok=True)
    # one texture repeat is 3 m: 1.5 m red, 1.5 m white
    row = [c for k in range(64) for c in ((190, 30, 30) if k < 32 else (235, 235, 235))]
    core.write_png(textures / "kerb_stripes.png", 64, 4, row * 4, channels=3)

    path = HERE / "visual_layer.usda"
    stage = new_stage(path)

    def uv(points, tile):
        return [(x / tile, y / tile) for x, y, _z in points]
    road = flat(0, 40, -4, 4)
    quad(stage, "road", road, material(stage, "STJ__surface__asphalt", (0.06, 0.06, 0.065), roughness=0.7),
         collision=True, uv=uv(road, 4.0))
    kerb = flat(0, 40, 4, 4.8, 0.0, 0.03)
    quad(stage, "kerb", kerb, material(stage, "Kerb_Paint", texture="textures/kerb_stripes.png", roughness=0.5),
         collision=True, uv=[(x / 3.0, 0.0 if y < 4.4 else 1.0) for x, y, _z in kerb])
    infield = flat(0, 40, 4.8, 20, 0.03, 0.03)
    quad(stage, "infield", infield, material(stage, "Infield_Grass", (0.07, 0.16, 0.03), roughness=0.95),
         uv=uv(infield, 2.0))
    doc = {
        "_metadata": meta("A track that carries its look beside its collision surface: road and painted kerb are both "
                          "(stj:collision), the infield only draws. The kerb paint is a texture on the kerb's material."),
        "track_info": {"name": "STJ visual layer", "type": "point_to_point", "fictional": True},
        "reference": centerline(40, 0),
        "geometry": {"meshes": [{"id": "track", "uri": path.name, "roles": ["collision", "visual"]}]},
        "surfaces": {"default": "grass",
                     "library": {**library(), "kerb": {"class": "kerb", "mf_scaling": {"LMUX": 0.9, "LMUY": 0.9}}},
                     "bindings": [{"mesh_ref": "track", "material": "Kerb_Paint", "surface": "kerb"}]},
        "environment": {"sky": {"model": "physical", "turbidity": 2.5, "clouds": {"coverage": 0.2, "kind": "cumulus"}},
                        "default_time": {"date": "2026-05-10", "local_time": "11:00"}},
    }
    save(stage, path, doc)


def main():
    if not core.have_pxr():
        raise SystemExit("make_features needs the pxr module: pip install usd-core")
    surface_maps()
    y_up()
    lane_materials()
    crg()
    visual_layer()
    print("feature examples written")


if __name__ == "__main__":
    main()
