def r(v, n=2):
    return round(v, n)


def dumps(doc):
    text = json.dumps(doc, indent=2, ensure_ascii=False)
    # put arrays of plain numbers on one line
    return re.sub(r"\[\s*([-0-9.eE+]+(?:,\s*[-0-9.eE+]+)*)\s*\]",
                  lambda m: "[" + ", ".join(x.strip() for x in m.group(1).split(",")) + "]", text) + "\n"


